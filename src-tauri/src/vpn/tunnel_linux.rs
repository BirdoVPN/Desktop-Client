    /// journal-driven recovery must remove it, beside the DNS restore.
    #[tokio::test(flavor = "multi_thread", worker_threads = 2)]
    #[ignore = "needs root in a private net+mount namespace: scripts/ci/linux-netns-tests.sh"]
    async fn a_killed_sessions_endpoint_route_is_removed_at_the_next_start() {
        assert_isolated();
        plain_resolv_conf();
        let before = resolv_conf();

        let (tunnel, key, _relay) = tunnel().await;
        tunnel
            .start(key)
            .await
            .expect("start() against the namespace's dummy uplink");
        let connected = net();
        assert!(
            connected.relay_routes.contains("uplink0"),
            "precondition: the endpoint route via the uplink is in: {connected:?}"
        );

        // What the next launch runs after a SIGKILL. It reads only its
        // records and the live state; the tunnel still being up is
        // irrelevant to it.
        crate::vpn::dns_journal::reconcile();
        let recovered = net();
        assert!(
            !recovered.relay_routes.contains("uplink0"),
            "the endpoint route a killed session left survived the next start's recovery: \
             {recovered:?}"
        );
        assert_eq!(
            resolv_conf(),
            before,
            "the recovery did not put resolv.conf back"
        );

        // Cleanup: the disconnect finds its endpoint route already gone, and
        // the crash record ends empty.
        tunnel.stop().await.expect("stop()");
        assert!(net().nothing_of_ours());
        assert!(
            !Path::new("/run/birdovpn/routes.json").exists(),
            "the crash record outlived the routes it describes"
        );
    }

    /// MR-2051: an earlier session left the endpoint route EXACTLY as this
    /// one adds it — killed before its crash record was written, or by a
    /// build without one — so this start's add hits "File exists". It used to
    /// be taken for someone else's route and outlive every later session
    /// (after a move to another network, pinning the relay to a gateway that
    /// was gone). It is ours: on the crash record while connected, and gone
    /// after the disconnect.
    #[tokio::test(flavor = "multi_thread", worker_threads = 2)]
    #[ignore = "needs root in a private net+mount namespace: scripts/ci/linux-netns-tests.sh"]
    async fn an_identical_endpoint_route_an_earlier_session_left_is_removed_at_disconnect() {
        assert_isolated();
        plain_resolv_conf();
        let before = resolv_conf();
        // What start() adds: the relay via the namespace's default gateway.
        // Removed on the way out whatever happens, so a failure here cannot
        // leave it behind for the tests that run after this one.
        const LEFTOVER: [&str; 5] = ["10.99.0.7/32", "via", "10.99.0.1", "dev", "uplink0"];
        struct Leftover;
        impl Drop for Leftover {
            fn drop(&mut self) {
                let _ = ip(&[&["route", "del"][..], &LEFTOVER[..]].concat());
            }
        }
        assert_eq!(LEFTOVER[0], format!("{RELAY}/32"));
        let (ok, out) = ip(&[&["route", "add"][..], &LEFTOVER[..]].concat());
        assert!(ok, "precondition: the leftover endpoint route: {out}");
        let _leftover = Leftover;

        let (tunnel, key, _relay) = tunnel().await;
        tunnel
            .start(key)
            .await
            .expect("start() against the namespace's dummy uplink");
        let record = std::fs::read_to_string("/run/birdovpn/routes.json").unwrap_or_default();
        assert!(
            record.contains(RELAY),
            "the leftover was not taken as ours: it is not on the crash record: {record:?}"
        );

        tunnel.stop().await.expect("stop()");
        let after = net();
        assert!(
            after.nothing_of_ours(),
            "the endpoint route an earlier session left survived the disconnect: {after:?}"
        );
        assert_eq!(resolv_conf(), before);
    }

    /// read(2)-family syscalls this process has made (`syscr`), what `perf
    /// stat -e syscalls:sys_enter_read` counts.
    fn read_syscalls() -> u64 {
        let io = std::fs::read_to_string("/proc/self/io").expect("/proc/self/io");
        io.lines()
            .find_map(|line| line.strip_prefix("syscr:"))
            .and_then(|count| count.trim().parse().ok())
            .expect("syscr in /proc/self/io")
    }

    /// Context switches over every thread this process has run, exited ones
    /// included: each is a thread going to sleep until it is woken again, or
    /// being put aside.
    fn context_switches() -> u64 {
        // SAFETY: an all-zero rusage is valid, and getrusage only fills it.
        let mut usage: libc::rusage = unsafe { std::mem::zeroed() };
        assert_eq!(unsafe { libc::getrusage(libc::RUSAGE_SELF, &mut usage) }, 0);
        (usage.ru_nvcsw + usage.ru_nivcsw) as u64
    }

    /// MR-2040, measured on a real device: a tunnel that is up and carries
    /// nothing. The old loop polled — a blocking-pool read of birdo0 every
    /// round and 500 µs / 5 ms sleeps between rounds, about 200 reads and
    /// 712 wakeups a second (agent L-1, 2026-10-14). The event-driven loop
    /// reads the device only when the kernel queued a packet, and otherwise
    /// wakes for boringtun's four timer ticks a second: under 10 reads a
    /// second (the audit's check: `perf stat -e syscalls:sys_enter_read` over
    /// an idle minute) and a few dozen wakeups at most. A datagram sent into
    /// birdo0 first proves the loop reads the real device. `BIRDO_IDLE_SECS`
    /// sets the idle window: 10 s by default, the audit's 60 s by hand.
    #[tokio::test(flavor = "multi_thread", worker_threads = 2)]
    #[ignore = "needs root in a private net+mount namespace: scripts/ci/linux-netns-tests.sh"]
    async fn an_idle_tunnel_neither_polls_its_device_nor_wakes_in_a_loop() {
        assert_isolated();
        plain_resolv_conf();
        let before = resolv_conf();
        let (tunnel, key, _relay) = tunnel().await;
        tunnel
            .start(key)
            .await
            .expect("start() against the namespace's dummy uplink");

        // 1000 bytes of UDP to the tunnel's DNS address, routed into birdo0 by
        // the halves: a 1028-byte IP packet the loop must read and encrypt.
        let sent = tunnel.get_stats().0;
        let probe = std::net::UdpSocket::bind("0.0.0.0:0").expect("a probe socket");
        probe
            .send_to(&[0x5a; 1000], "10.66.0.53:53")
            .expect("send into the tunnel");
        let encrypted = || tunnel.get_stats().0 >= sent + 1028;
        assert!(
            wait_until(Duration::from_secs(5), encrypted).await,
            "the packet loop never read the datagram from birdo0: {:?}",
            tunnel.get_stats()
        );

        let secs = std::env::var("BIRDO_IDLE_SECS")
            .ok()
            .and_then(|s| s.parse::<u64>().ok())
            .unwrap_or(10);
        tokio::time::sleep(Duration::from_secs(1)).await;
        // `/proc/self/io` is read last on the way in and first on the way
        // out, so the window counts none of the measuring's own reads.
        let switches_at = context_switches();
        let reads_at = read_syscalls();
        tokio::time::sleep(Duration::from_secs(secs)).await;
        let reads = read_syscalls() - reads_at;
        let switches = context_switches() - switches_at;
        let reads_per_s = reads as f64 / secs as f64;
        let wakeups_per_s = switches as f64 / secs as f64;
        eprintln!(
            "MR-2040: an idle tunnel over {secs} s: {reads} read syscalls ({reads_per_s:.1}/s), \
             {switches} context switches ({wakeups_per_s:.1}/s)"
        );
        assert!(
            reads_per_s < 10.0,
            "the idle tunnel still polls birdo0: {reads_per_s:.1} reads/s"
        );
        assert!(
            wakeups_per_s < 50.0,
            "the idle tunnel still wakes in a loop: {wakeups_per_s:.1} context switches/s"
        );

        tunnel.stop().await.expect("stop()");
        let after = net();
        assert!(after.nothing_of_ours(), "{after:?}");
        assert_eq!(resolv_conf(), before);
    }

    /// MR-2040, the inbound half: a packet the relay sends down the tunnel.
    /// The loop's relay-socket arm must wake on the socket's readiness,
    /// decrypt the datagram and write the packet to birdo0, where the kernel
    /// hands it to the local socket it is addressed to — the half downloads
    /// depend on. Nothing else here gives that arm a packet: start()'s
    /// handshake reads its own answer, and the idle windows never reach a
    /// rekey. The relay echoes the datagram the probe sends into the tunnel;
    /// the echo must come out of birdo0, and the tunnel must count it.
    #[tokio::test(flavor = "multi_thread", worker_threads = 2)]
    #[ignore = "needs root in a private net+mount namespace: scripts/ci/linux-netns-tests.sh"]
    async fn a_packet_from_the_relay_is_decrypted_onto_birdo0() {
        assert_isolated();
        plain_resolv_conf();
        let before = resolv_conf();
        let (tunnel, key, _relay) = tunnel().await;
        tunnel
            .start(key)
            .await
            .expect("start() against the namespace's dummy uplink");

        let (_, received, _, packets) = tunnel.get_stats();
        // 1000 bytes of UDP to the tunnel's DNS address, routed into birdo0
        // by the halves; the relay sends the same 1028-byte packet back,
        // from 10.66.0.53:53 to this socket.
        let probe = tokio::net::UdpSocket::bind("0.0.0.0:0")
            .await
            .expect("a probe socket");
        probe
            .send_to(&[0xa5; 1000], "10.66.0.53:53")
            .await
            .expect("send into the tunnel");
        let mut buf = [0u8; 2048];
        let echo = tokio::time::timeout(Duration::from_secs(5), probe.recv_from(&mut buf)).await;
        let stats = tunnel.get_stats();
        tunnel.stop().await.expect("stop()");

        let Ok(echo) = echo else {
            panic!(
                "the relay's packet never came out of birdo0: the packet loop did not decrypt \
                 it onto the device ({stats:?})"
            );
        };
        let (n, from) = echo.expect("receive the echo");
        assert_eq!(from.to_string(), "10.66.0.53:53");
        assert_eq!(&buf[..n], &[0xa5; 1000][..]);
        assert!(
            stats.1 >= received + 1028 && stats.3 > packets,
            "the tunnel did not count the packet it wrote to birdo0: {stats:?}"
        );
        let after = net();
        assert!(after.nothing_of_ours(), "{after:?}");
        assert_eq!(resolv_conf(), before);
    }
