    /// Refuse to run outside the namespace the CI script builds. PID 1 is the
    /// host's init (the script does not unshare the PID namespace), so a
    /// namespace that is still PID 1's is the host's.
    fn assert_isolated() {
        for kind in ["net", "mnt"] {
            let ours = std::fs::read_link(format!("/proc/self/ns/{kind}")).ok();
            let host = std::fs::read_link(format!("/proc/1/ns/{kind}")).ok();
            assert!(
                ours.is_some() && host.is_some() && ours != host,
                "refusing to run outside a private {kind} namespace: these tests rewrite routes \
                 and /etc/resolv.conf. Run scripts/ci/linux-netns-tests.sh under sudo unshare."
            );
        }
        assert_eq!(
            std::env::var("BIRDO_NETNS_TESTS").as_deref(),
            Ok("1"),
            "not started by scripts/ci/linux-netns-tests.sh"
        );
    }

    fn ip(args: &[&str]) -> (bool, String) {
        match cmd("ip").args(args).output() {
            Ok(o) => (
                o.status.success(),
                format!(
                    "{}{}",
                    String::from_utf8_lossy(&o.stdout),
                    String::from_utf8_lossy(&o.stderr)
                ),
            ),
            Err(e) => (false, e.to_string()),
        }
    }

    /// The routing state these tests reason about, read in-process: the TUN
    /// fd dies with the process, so only a read taken while the process is
    /// alive can see a leaked device.
    #[derive(Debug)]
    struct Net {
        birdo0: bool,
        /// 0.0.0.0/1 and 128.0.0.0/1, whichever device holds them.
        halves: String,
        /// Host routes to the relay, whichever device holds them.
        relay_routes: String,
    }

    fn net() -> Net {
        Net {
            birdo0: ip(&["link", "show", TUN_DEVICE_NAME]).0,
            halves: format!(
                "{}{}",
                ip(&["route", "show", "0.0.0.0/1"]).1,
                ip(&["route", "show", "128.0.0.0/1"]).1
            ),
            relay_routes: ip(&["route", "show", RELAY]).1,
        }
    }

    impl Net {
        fn nothing_of_ours(&self) -> bool {
            !self.birdo0
                && !self.halves.contains(TUN_DEVICE_NAME)
                && !self.relay_routes.contains("uplink0")
        }
    }

    /// A WireGuard relay that answers one client's handshake. start() builds
    /// its WireGuard session, a real handshake, BEFORE it creates a route or
    /// touches DNS: against a relay that never answers, every start() here
    /// failed with "Handshake timeout" and no test reached the teardown it is
    /// about. Same responder as wireguard_new's handshake_tests, bound on
    /// RELAY. Aborted on drop.
    ///
    /// Once the session carries data it also ECHOES every UDP datagram it
    /// receives through the tunnel back down it ([`udp_echo`]), encrypted, so
    /// the packet loop's inbound half (the relay socket's readiness -> decrypt
    /// -> birdo0) carries a packet of its own in these tests (MR-2040).
    struct Relay {
        endpoint: String,
        server_public_b64: String,
        task: tokio::task::JoinHandle<()>,
    }

    impl Drop for Relay {
        fn drop(&mut self) {
            self.task.abort();
        }
    }

    async fn relay(client: boringtun::x25519::PublicKey) -> Relay {
        use base64::Engine as _;
        use boringtun::noise::{Tunn, TunnResult};
        let server_secret = crate::utils::os_rng::x25519_static_secret();
        let server_public = boringtun::x25519::PublicKey::from(&server_secret);
        let mut tunn = Tunn::new(server_secret, client, None, None, 1, None);
        let socket = tokio::net::UdpSocket::bind(format!("{RELAY}:0"))
            .await
            .expect("bind the relay on RELAY: the script puts it on lo");
        let endpoint = socket.local_addr().expect("the relay's port").to_string();
        let task = tokio::spawn(async move {
            let mut buf = [0u8; 2048];
            let mut out = [0u8; 2048];
            let mut sealed = [0u8; 2048];
            loop {
                let Ok((n, from)) = socket.recv_from(&mut buf).await else {
                    return;
                };
                match tunn.decapsulate(Some(from.ip()), &buf[..n], &mut out) {
                    TunnResult::WriteToNetwork(reply) => {
                        let _ = socket.send_to(reply, from).await;
                    }
                    // A data packet: the session is current, so it can carry
                    // one back.
                    TunnResult::WriteToTunnelV4(packet, _) => {
                        let Some(echo) = udp_echo(packet) else {
                            continue;
                        };
                        if let TunnResult::WriteToNetwork(data) =
                            tunn.encapsulate(&echo, &mut sealed)
                        {
                            let _ = socket.send_to(data, from).await;
                        }
                    }
                    _ => {}
                }
            }
        });
        Relay {
            endpoint,
            server_public_b64: base64::engine::general_purpose::STANDARD
                .encode(server_public.as_bytes()),
            task,
        }
    }

    /// The answer to an IPv4/UDP `packet` that came through the tunnel: the
    /// same datagram from where it was sent to back to its sender (addresses
    /// and ports swapped), with a fresh header checksum and no UDP checksum
    /// (optional over IPv4). `None` for anything else.
    fn udp_echo(packet: &[u8]) -> Option<Vec<u8>> {
        let ihl = usize::from(packet.first()? & 0x0f) * 4;
        if packet[0] >> 4 != 4 || ihl < 20 || packet.len() < ihl + 8 || packet[9] != 17 {
            return None;
        }
        let mut echo = packet.to_vec();
        echo[12..16].copy_from_slice(&packet[16..20]);
        echo[16..20].copy_from_slice(&packet[12..16]);
        echo[ihl..ihl + 2].copy_from_slice(&packet[ihl + 2..ihl + 4]);
        echo[ihl + 2..ihl + 4].copy_from_slice(&packet[ihl..ihl + 2]);
        echo[ihl + 6..ihl + 8].fill(0);
        echo[8] = 64; // TTL
        echo[10..12].fill(0);
        let sum = echo[..ihl]
            .chunks(2)
            .map(|word| u32::from(u16::from_be_bytes([word[0], word[1]])))
            .sum::<u32>();
        let folded = (sum & 0xffff) + (sum >> 16);
        let checksum = !(((folded & 0xffff) + (folded >> 16)) as u16);
        echo[10..12].copy_from_slice(&checksum.to_be_bytes());
        Some(echo)
    }

