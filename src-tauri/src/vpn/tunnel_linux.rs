/// Run a command (no special flags needed on Linux — no console window issue)
fn cmd(program: &str) -> Command {
    crate::utils::hidden_cmd(program)
}

/// TUN device name prefix
const TUN_DEVICE_NAME: &str = "birdo0";

/// First line configure_dns writes when it pins /etc/resolv.conf. Also used to
/// RECOGNISE our own pin on unwind paths where the `Ok(pinned)` flag never
/// reached the caller (configure_dns erroring after the write, or a cancelled
/// start()) — see `resolv_conf_is_ours`.
const RESOLV_CONF_MARKER: &str = "# Generated by Birdo VPN";

/// F-001: dedicated chain for the steady-state IPv6 leak block. Deliberately
/// SEPARATE from the kill switch's BIRDO_KILLSWITCH chain so the two never
/// interfere — this block must persist for the whole Connected session
/// regardless of the kill-switch preference, whereas the kill-switch chain is
/// preference-gated and released by disarm/give-up/settings-toggle.
const IPV6_BLOCK_CHAIN: &str = "BIRDO_IPV6_LEAK_BLOCK";

/// Run an ip6tables command, tolerating ip6tables being absent (IPv4-only host).
/// Mirrors firewall_linux.rs's ip6tables() so behaviour is identical.
fn ip6t(args: &[&str]) -> Result<(), String> {
    // `-w`: wait for the xtables lock instead of failing instantly under
    // contention (firewalld, docker) — same as firewall_linux.rs's helpers.
    match cmd("ip6tables").arg("-w").args(args).output() {
        Ok(o) if o.status.success() => Ok(()),
        Ok(o) => Err(format!(
            "ip6tables {} failed: {}",
            args.join(" "),
            String::from_utf8_lossy(&o.stderr).trim()
        )),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => {
            tracing::debug!("ip6tables not present — skipping IPv6 leak block (IPv4-only host)");
            Ok(())
        }
        Err(e) => Err(format!("ip6tables spawn failed: {e}")),
    }
}

/// F-001: install a default-deny IPv6 egress block for the whole connect window.
///
/// Without this, any IPv6-capable app egresses via the physical NIC's untouched
/// IPv6 default route while the UI reports "Protected" — a continuous
/// de-anonymisation leak the kill switch never catches (WireGuard never drops,
/// so nothing trips). Windows has done this since the LEAK-2 fix (tunnel.rs);
/// this is the Linux port.
///
/// This is the DEFAULT state, not the final one. It is installed unconditionally
/// at tunnel start so every failure path fails closed, and lifted by
/// `remove_ipv6_leak_block` only once `configure_ipv6` has actually put the
/// tunnel's own v6 address and routes in place — which happens only when the
/// backend issued a `client_ipv6` (i.e. the node is genuinely dual-stack).
/// On an IPv4-only node the block simply stays for the whole session.
///
/// Loopback, link-local and NDP/ICMPv6 stay permitted so the host keeps working;
/// everything routable is dropped. Idempotent (flush + recreate each call).
pub(crate) fn install_ipv6_leak_block() -> Result<(), String> {
    let _ = ip6t(&["-N", IPV6_BLOCK_CHAIN]); // create (ignore "already exists")
    let _ = ip6t(&["-F", IPV6_BLOCK_CHAIN]); // clean slate
    ip6t(&["-A", IPV6_BLOCK_CHAIN, "-o", "lo", "-j", "ACCEPT"])?;
    // Link-local and link-scoped multicast only: this covers NDP (NS/NA/RS/RA),
    // DAD, MLD and DHCPv6, which is everything the host needs to stay functional.
    // NOTE: deliberately NO blanket `-p ipv6-icmp ACCEPT`. That would permit
    // ICMPv6 echo to GLOBAL destinations, i.e. `ping6 <any host>` would still
    // egress the physical NIC and disclose the real IPv6 address — a smaller
    // version of the very leak this chain exists to close. Inbound ICMPv6 (PMTUD
    // "Packet Too Big") is unaffected: this chain is hooked into OUTPUT only.
    ip6t(&["-A", IPV6_BLOCK_CHAIN, "-d", "fe80::/10", "-j", "ACCEPT"])?;
    ip6t(&["-A", IPV6_BLOCK_CHAIN, "-d", "ff02::/16", "-j", "ACCEPT"])?;
    // REJECT, not DROP: the packet is still never allowed out (identical leak
    // protection — the ICMPv6 rejection is generated locally), but the sender
    // fails IMMEDIATELY instead of waiting out a TCP timeout. A silent DROP
    // stalled our OWN dual-stack control-plane HTTPS (api.birdo.app publishes an
    // AAAA) and DoH until the request timeout, so a server switch could not
    // fetch its new config. Fall back to DROP if the REJECT target is
    // unavailable (some minimal kernels lack ip6t_REJECT) — never leave IPv6
    // unblocked just because we could not install the nicer variant.
    if ip6t(&[
        "-A",
        IPV6_BLOCK_CHAIN,
        "-j",
        "REJECT",
        "--reject-with",
        "icmp6-adm-prohibited",
    ])
    .is_err()
    {
        ip6t(&["-A", IPV6_BLOCK_CHAIN, "-j", "DROP"])?;
    }
    // Jump OUTPUT -> our chain (delete first so repeated starts don't stack).
    let _ = ip6t(&["-D", "OUTPUT", "-j", IPV6_BLOCK_CHAIN]);
    ip6t(&["-I", "OUTPUT", "1", "-j", IPV6_BLOCK_CHAIN])?;
    tracing::info!("F-001: IPv6 egress blocked for the connect window");
    Ok(())
}

/// F-001: lift the IPv6 block at teardown. Best-effort — never fail teardown.
///
/// Also used to reconcile state a crashed or failed run left behind: the chain
/// name is ours alone, so removing it is unconditionally safe and idempotent.
pub(crate) fn remove_ipv6_leak_block() {
    let _ = ip6t(&["-D", "OUTPUT", "-j", IPV6_BLOCK_CHAIN]);
    let _ = ip6t(&["-F", IPV6_BLOCK_CHAIN]);
    let _ = ip6t(&["-X", IPV6_BLOCK_CHAIN]);
    tracing::info!("F-001: IPv6 egress block removed");
}

/// Stores original DNS and default route info for restoration on disconnect
#[derive(Debug, Clone)]
struct NetworkSnapshot {
    /// Original DNS servers from /etc/resolv.conf or systemd-resolved
    dns_servers: Vec<String>,
    /// Original default gateway
    default_gateway: Option<String>,
    /// Original default interface (e.g. "eth0", "wlan0")
    default_interface: Option<String>,
    /// Whether systemd-resolved is available
    uses_systemd_resolved: bool,
    /// Original resolv.conf contents for fallback restoration
    resolv_conf_backup: Option<String>,
    /// MR-2018: what /etc/resolv.conf pointed at when it was a SYMLINK
    /// (NetworkManager, resolvconf, WSL's /mnt/wsl/resolv.conf), as read_link
    /// returned it. configure_dns replaces the link with a regular file, so
    /// restoring only `resolv_conf_backup`'s bytes froze the host on a copy:
    /// the link's owner kept updating its target and nothing read it any more.
    /// `None` when the file was not a symlink.
    resolv_conf_link: Option<std::path::PathBuf>,
    /// True once configure_dns has OVERWRITTEN /etc/resolv.conf this session.
    /// This — not `uses_systemd_resolved` — is what drives the file restore on
    /// disconnect: the two signals disagree on real hosts (resolved unit
    /// active but resolv.conf a plain file), and restoring off the wrong one
    /// left the host pointed at dead tunnel resolvers.
    resolv_conf_pinned: bool,
}

/// Linux TUN tunnel for WireGuard VPN
pub struct LinuxTunnel {
    config: VpnConfig,
    running: Arc<AtomicBool>,
    bytes_sent: Arc<AtomicU64>,
    bytes_received: Arc<AtomicU64>,
    packets_sent: Arc<AtomicU64>,
    packets_received: Arc<AtomicU64>,
    wg_session: Arc<RwLock<Option<WireGuardSession>>>,
    shutdown_tx: Arc<RwLock<Option<mpsc::Sender<()>>>>,
    /// The TUN device name (e.g. "birdo0")
    tun_name: Arc<RwLock<Option<String>>>,
    /// The TUN device's file descriptor, shared with the packet loop and each
    /// of its in-flight blocking reads/writes (MR-820, see `device_fd`).
    tun_fd: Arc<DeviceSlot<OwnedFd>>,
    /// Network snapshot for restoration on disconnect
    network_snapshot: Arc<RwLock<Option<NetworkSnapshot>>>,
    /// Whether to allow local network access while VPN is active
    local_network_sharing: bool,
    /// Every route THIS session added, recorded the moment its add succeeded,
    /// and removed (qualified exactly as it was added) by stop(), the failed-
    /// start unwind and Drop. A std Mutex, never held across an await, so Drop
    /// can take it.
    owned_routes: Arc<OwnedRoutes>,
    /// JoinHandle of the spawned packet loop.
    ///
    /// P1-dk-tun-fd-close-race: stop() JOINS this task before closing the TUN
    /// fd. Joining the task alone did not join the blocking reads/writes it
    /// had already handed off (MR-820); those now hold the fd themselves, and
    /// the close waits for them (`device_fd::close_when_idle`).
    packet_loop: Arc<RwLock<Option<tokio::task::JoinHandle<()>>>>,
}

impl LinuxTunnel {
    /// Create a new TUN tunnel with the given VPN configuration.
    ///
    /// MR-822: takes `config` by move (it used to clone it). The config holds
    /// no private key; that is handed to [`start`](Self::start).
    pub async fn create(config: VpnConfig, local_network_sharing: bool) -> Result<Self, String> {
        validate_config(&config)?;

        Ok(Self {
            config,
            running: Arc::new(AtomicBool::new(false)),
            bytes_sent: Arc::new(AtomicU64::new(0)),
            bytes_received: Arc::new(AtomicU64::new(0)),
            packets_sent: Arc::new(AtomicU64::new(0)),
            packets_received: Arc::new(AtomicU64::new(0)),
            wg_session: Arc::new(RwLock::new(None)),
            shutdown_tx: Arc::new(RwLock::new(None)),
            tun_name: Arc::new(RwLock::new(None)),
            tun_fd: Arc::new(RwLock::new(None)),
            network_snapshot: Arc::new(RwLock::new(None)),
            local_network_sharing,
            owned_routes: Arc::new(OwnedRoutes::default()),
            packet_loop: Arc::new(RwLock::new(None)),
        })
    }

    /// Start the tunnel: create TUN device, configure routes/DNS, start packet loop.
    ///
    /// MR-822: `private_key` moves into the WireGuard session, and the tunnel
    /// keeps no copy. A start that fails before the session is built drops it,
    /// which wipes it.
    pub async fn start(&self, private_key: WgPrivateKey) -> Result<(), String> {
        tracing::info!("Starting Linux TUN tunnel");

        if !crate::utils::elevation::is_elevated() {
            tracing::warn!("Tunnel requires root privileges for TUN/route configuration");
        }

        // Snapshot current network config for restoration
        let snapshot = capture_network_snapshot().await?;
        tracing::info!(
            "Captured network snapshot: gw={:?}, iface={:?}",
            snapshot.default_gateway.as_deref().map(redact_ip),
            snapshot.default_interface
        );
        *self.network_snapshot.write().await = Some(snapshot);

        // Create the TUN device
        let (tun_name, tun_fd) =
            create_tun_device().map_err(|e| format!("Failed to create TUN device: {}", e))?;
        tracing::info!("Created TUN device: {}", tun_name);

        *self.tun_name.write().await = Some(tun_name.clone());
        *self.tun_fd.write().await = Some(Arc::new(tun_fd));

        // Create WireGuard session BEFORE configuring routes.
        //
        // P1-dk-linux-no-drop-fd-leak-blackhole: from here on, every error
        // return goes through unwind_failed_start() — the fd stored above must
        // never outlive a failed start (the device it keeps alive owns the
        // split-default routes with no packet loop behind them: an IPv4
        // blackhole), and partially-installed routes/DNS must be rolled back.
        // Mirrors tunnel_macos.rs's close_fd_on_err, but reuses stop() so the
        // unwind cannot drift from the real teardown.
        let wg_session = match WireGuardSession::new(
            private_key,
            &self.config.server_public_key,
            &self.config.endpoint,
            self.config.preshared_key.as_deref(),
            self.config.persistent_keepalive,
        )
        .await
        {
            Ok(session) => session,
            Err(e) => {
                self.unwind_failed_start().await;
                return Err(format!("Failed to create WireGuard session: {}", e));
            }
        };
        tracing::info!("WireGuard session created");

        let endpoint_ip = wg_session.endpoint_ip();
        tracing::info!(
            "WireGuard endpoint IP: {}",
            redact_ip(&endpoint_ip.to_string())
        );

        // Configure the TUN interface IP and bring it up
        if let Err(e) = configure_tun_address(&tun_name, &self.config.client_ip, &self.config.mtu) {
            self.unwind_failed_start().await;
            return Err(e);
        }

        // Configure routing
        if let Err(e) = configure_routes(
            &tun_name,
            &endpoint_ip.to_string(),
            &self.config.allowed_ips,
            self.local_network_sharing,
            &self.owned_routes,
        )
        .await
        {
            // configure_routes can fail MID-LOOP with the endpoint route and
            // 0.0.0.0/1 already installed. Each route it added is already in
            // owned_routes, so the unwind (via stop()) deletes exactly those —
            // and nothing that merely shares a prefix with them: the collision
            // that failed this start is usually ANOTHER VPN's 0.0.0.0/1, which
            // an unqualified delete used to remove (bug B). Closing the fd
            // alone would leave the endpoint/LAN routes pointing at a stale
            // gateway.
            self.unwind_failed_start().await;
            return Err(e);
        }

        // F-001 (P0): block IPv6 egress for the whole Connected session. Done here
        // — at tunnel start, INDEPENDENT of the kill-switch enabled/lockdown
        // setting — exactly as Windows does (tunnel.rs LEAK-2). The kill switch
        // cannot cover this: it is preference-gated (and released on disarm/
        // give-up), and an IPv6 leak never drops the (IPv4-only) tunnel so the
        // reactive path never triggers.
        //
        // Block FIRST, unconditionally, then lift only if we can actually carry
        // IPv6 — so every failure path between here and a working dual-stack
        // tunnel fails CLOSED.
        if let Err(e) = install_ipv6_leak_block() {
            self.unwind_failed_start().await;
            return Err(e);
        }

        // Dual-stack: the fleet DOES have routable IPv6 now (nodes provisioned
        // with enable_ipv6 get a real /64), so when the backend issues a
        // client_ipv6 the correct behaviour is to ROUTE IPv6 through the tunnel,
        // not to black-hole it. The tunnel's own v6 address and routes go in
        // FIRST, with the block still in force (ip6tables filters packets, it
        // does not stop address or route configuration), and the block is
        // lifted only once that succeeded. If it fails, nothing was lifted, so
        // nothing needs re-blocking: IPv6 simply stays blocked. tunnel.rs
        // (Windows) uses the same order since W15.
        //
        // Absent client_ipv6 the block simply stays in force, which is the
        // leak-safe behaviour for an IPv4-only node.
        if self.config.client_ipv6.is_some() {
            match configure_ipv6(&tun_name, &self.config).await {
                Ok(()) => {
                    remove_ipv6_leak_block();
                    tracing::info!("IPv6 routed through the tunnel (dual-stack node)");
                }
                Err(e) => {
                    tracing::warn!("IPv6 routing setup failed ({}); leaving IPv6 blocked", e);
                }
            }
        }

        // Configure DNS
        let snapshot = self.network_snapshot.read().await;
        let uses_resolved = snapshot.as_ref().is_some_and(|s| s.uses_systemd_resolved);
        drop(snapshot);
        let pinned = match configure_dns(&self.config.dns, &tun_name, uses_resolved).await {
            Ok(pinned) => pinned,
            Err(e) => {
                // configure_dns can fail AFTER pinning /etc/resolv.conf (the
                // resolvectl step errors once the file is already written);
                // unwind_failed_start detects the marker and restores the backup.
                self.unwind_failed_start().await;
                return Err(e);
            }
        };
        if pinned {
            // Record "we overwrote /etc/resolv.conf" so restore_dns puts the
            // backup back — this flag, not uses_systemd_resolved, drives the
            // file restore (the two disagree on real hosts; see NetworkSnapshot).
            if let Some(snap) = self.network_snapshot.write().await.as_mut() {
                snap.resolv_conf_pinned = true;
            }
        }

        // Store WireGuard session
        *self.wg_session.write().await = Some(wg_session);
        self.running.store(true, Ordering::SeqCst);

        // Create shutdown channel
        let (shutdown_tx, shutdown_rx) = mpsc::channel::<()>(1);
        *self.shutdown_tx.write().await = Some(shutdown_tx);

        // Start packet processing loop
        let running = self.running.clone();
        let bytes_sent = self.bytes_sent.clone();
        let bytes_received = self.bytes_received.clone();
        let packets_sent = self.packets_sent.clone();
        let packets_received = self.packets_received.clone();
        let wg_session = self.wg_session.clone();
        // The loop's own reference (MR-820), taken from the slot so start()
        // keeps none: an unwind's close must not wait on a local of ours.
        // Bound first: the read guard must be gone before the unwind's close
        // takes the write lock.
        let loop_fd = self.tun_fd.read().await.clone();
        let Some(fd) = loop_fd else {
            self.unwind_failed_start().await;
            return Err("The TUN device was closed before the packet loop started".to_string());
        };

        let loop_handle = tokio::spawn(async move {
            Self::packet_loop(
                fd,
                wg_session,
                running,
                bytes_sent,
                bytes_received,
                packets_sent,
                packets_received,
                shutdown_rx,
            )
            .await;
        });
        // Keep the handle so stop() can join the loop before closing the fd
        // (P1-dk-tun-fd-close-race).
        *self.packet_loop.write().await = Some(loop_handle);

        tracing::info!("Linux tunnel started successfully");
        Ok(())
    }

    /// Unwind a partially-configured start() on its error path.
    ///
    /// P1-dk-linux-no-drop-fd-leak-blackhole: every `?` after the TUN fd was
    /// stored used to return with the fd (and whatever routes/DNS had gone in)
    /// left behind — the device survived, still owning the split-default
    /// routes with no packet loop: a total IPv4 blackhole plus one leaked fd
    /// per failed connect. This reuses stop() — unconditional and best-effort
    /// on Linux — so the unwind removes exactly the subset of state the failed
    /// start managed to install and can never drift from the real teardown.
    async fn unwind_failed_start(&self) {
        // configure_dns can fail AFTER overwriting /etc/resolv.conf (the
        // resolvectl step errors once the file is already written), and its
        // Ok(pinned) flag is lost with the Err — so recognise our own marker
        // directly and record it, which is what drives restore_dns's file
        // restore inside stop().
        if resolv_conf_is_ours() {
            if let Some(snap) = self.network_snapshot.write().await.as_mut() {
                snap.resolv_conf_pinned = true;
            }
        }
        if let Err(e) = self.stop().await {
            tracing::warn!("Cleanup after a failed tunnel start also failed: {}", e);
        }
    }

    /// Stop the tunnel and restore network configuration.
    pub async fn stop(&self) -> Result<(), String> {
        tracing::info!("Stopping Linux TUN tunnel");

        self.running.store(false, Ordering::SeqCst);

        // Signal the packet loop to stop
        if let Some(tx) = self.shutdown_tx.write().await.take() {
            let _ = tx.send(()).await;
        }

        // P1-dk-tun-fd-close-race: JOIN the packet loop before the fd close
        // below. The fd is O_NONBLOCK, so the loop drains within one iteration
        // of the shutdown signal; the timeout is a safety valve only. If it
        // ever fires we abort the task and fall through to the close anyway —
        // a stuck loop must not leave the device alive owning the half-default
        // routes (that is the frozen-switch blackhole).
        //
        // MR-820: the task join does not cover a read the loop had already
        // handed to the blocking pool (the select! detaches it when shutdown
        // wins). Each of those holds its own reference to the fd now, and the
        // close at the end of stop() waits for them.
        if let Some(handle) = self.packet_loop.write().await.take() {
            let abort = handle.abort_handle();
            if tokio::time::timeout(std::time::Duration::from_secs(5), handle)
                .await
                .is_err()
            {
                abort.abort();
                tracing::warn!(
                    "Packet loop did not exit within 5s of shutdown — aborted it; \
                     closing the TUN fd regardless"
                );
            }
        }

        // Restore DNS. The teardown continues either way; restore_dns keeps
        // the journal for anything it could not verify, so the next start
        // retries.
        if let Some(snapshot) = self.network_snapshot.read().await.as_ref() {
            crate::vpn::dns_journal::settle(restore_dns(snapshot), crate::vpn::dns_journal::clear);
        }

        // F-001: lift the IPv6 block. Best-effort so it can never fail teardown
        // (a stuck block would leave the host without IPv6 after disconnect).
        remove_ipv6_leak_block();

        // Remove the routes this session added — only those, each qualified
        // exactly as it was added, so a route that merely shares a prefix with
        // one of ours (another VPN's 0.0.0.0/1, the host's own endpoint route)
        // is never touched.
        remove_owned_routes(take_owned_routes(&self.owned_routes));

        // Close the TUN file descriptor (kernel auto-removes the device) — once
        // no in-flight blocking read/write still holds it (MR-820). Closing
        // under one used to hand its number to the kernel's free pool while
        // the syscall had yet to run.
        match device_fd::close_when_idle(&self.tun_fd, device_fd::IN_FLIGHT_WAIT).await {
            CloseOutcome::Closed => tracing::info!("Closed TUN file descriptor"),
            CloseOutcome::Deferred => tracing::warn!(
                "TUN fd still held by in-flight I/O after {:?} — released our reference; it \
                 closes when that I/O returns",
                device_fd::IN_FLIGHT_WAIT
            ),
            CloseOutcome::Empty => {}
        }

        *self.tun_name.write().await = None;
        *self.wg_session.write().await = None;

        tracing::info!("Linux tunnel stopped successfully");
        Ok(())
    }

    /// Get tunnel statistics: (bytes_sent, bytes_received, packets_sent, packets_received)
    pub fn get_stats(&self) -> (u64, u64, u64, u64) {
        (
            self.bytes_sent.load(Ordering::Relaxed),
            self.bytes_received.load(Ordering::Relaxed),
            self.packets_sent.load(Ordering::Relaxed),
            self.packets_received.load(Ordering::Relaxed),
        )
    }

    /// Get current latency in milliseconds.
    pub async fn get_latency_ms(&self) -> Option<u32> {
        if let Some(session) = self.wg_session.read().await.as_ref() {
            session.get_latency_ms().await
        } else {
            None
        }
    }

    /// Time since the last completed WireGuard handshake (W1-002). `None` once
    /// the WireGuard session is gone (the tunnel is being stopped).
    pub async fn handshake_age(&self) -> Option<std::time::Duration> {
        self.wg_session
            .read()
            .await
            .as_ref()
            .map(|session| session.handshake_age())
    }

    /// Start a handshake now unless one is in flight (see
    /// `WireGuardSession::force_handshake`).
    pub async fn force_handshake(&self) {
        if let Some(session) = self.wg_session.read().await.as_ref() {
            session.force_handshake().await;
        }
    }

    /// Packet processing loop: read from TUN, encrypt via WireGuard, send to server.
    ///
    /// Linux TUN with IFF_NO_PI provides raw IP packets — no protocol header unlike macOS utun.
    ///
    /// OPEN-WORK F6: the TUN read reuses ONE owned buffer across iterations
    /// (the macOS loop's pattern, tunnel_macos.rs) instead of allocating a
    /// fresh 64 KiB `Vec` per iteration. The loop spins once per packet in
    /// either direction and — before idle backoff kicks in — once per
    /// EAGAIN poll, so the old `vec![0u8; MAX_PACKET_SIZE]` inside the
    /// per-iteration `spawn_blocking` closure was a 64 KiB alloc + free (and
    /// on every non-idle iteration a page fault or memset for the pages the
    /// kernel actually filled) per packet, on the hot path, for the whole
    /// session. See [`tun_read_owned`].
    ///
    /// MR-820: every blocking read/write gets its own clone of `tun_fd` and
    /// holds it for the length of the syscall, so the descriptor cannot be
    /// closed (and its number recycled) under one the loop has detached.
    #[allow(clippy::too_many_arguments)] // shared session handles, moved into the task once
    async fn packet_loop(
        tun_fd: SharedFd,
        wg_session: Arc<RwLock<Option<WireGuardSession>>>,
        running: Arc<AtomicBool>,
        bytes_sent: Arc<AtomicU64>,
        bytes_received: Arc<AtomicU64>,
        packets_sent: Arc<AtomicU64>,
        packets_received: Arc<AtomicU64>,
        mut shutdown_rx: mpsc::Receiver<()>,
    ) {
        tracing::info!("Packet loop started on TUN fd={}", tun_fd.as_raw_fd());

        const MAX_PACKET_SIZE: usize = 65536;

        // Same cadence Windows uses (tunnel.rs). 250ms is comfortably finer than
        // boringtun's shortest timer, so no deadline is ever missed.
        // Idle backoff, mirroring Windows (tunnel.rs). Both fds are O_NONBLOCK
        // and recv_packet returns Ok(None) immediately on WouldBlock, so an idle
        // tunnel previously spun a core at 100% and churned the blocking pool
        // with a spawn_blocking round trip per iteration, forever. Any packet in
        // either direction resets the counter, so only the FIRST packet after a
        // sustained idle pays the extra latency.
        let mut idle_cycles: u32 = 0;
        const IDLE_THRESHOLD: u32 = 100;
        const DEEP_IDLE_THRESHOLD: u32 = 2_000;
        const SLOW_POLL_US: u64 = 500;
        const DEEP_POLL_US: u64 = 5_000;
        // Drain up to this many decrypted packets per wake, so a burst is not
        // paced one packet per loop iteration.
        const MAX_BATCH_SIZE: usize = 64;
        let mut last_timer_update = std::time::Instant::now();
        const TIMER_INTERVAL: std::time::Duration = std::time::Duration::from_millis(250);

        // The one read buffer for the whole session (F6). It is moved into the
        // blocking read task each iteration and handed back with the byte count.
        let mut read_buf = vec![0u8; MAX_PACKET_SIZE];

        loop {
            let mut did_work = false;
            if !running.load(Ordering::SeqCst) {
                tracing::info!("Packet loop: running flag cleared, exiting");
                break;
            }

            // The buffer normally comes back from the blocking task. If it did
            // not (the task failed to join — the shutdown arm breaks the loop, so
            // it never reaches here), restore it so `read` is never issued
            // against a zero-length slice; that would return 0 forever and read
            // as a silent EOF.
            if read_buf.len() != MAX_PACKET_SIZE {
                read_buf = vec![0u8; MAX_PACKET_SIZE];
            }

            tokio::select! {
                _ = shutdown_rx.recv() => {
                    tracing::info!("Packet loop: shutdown signal received");
                    break;
                }
                // Read from TUN (async via spawn_blocking for the fd read). The
                // owned buffer is moved in and returned, never reallocated.
                // The closure owns a reference to the fd until the read returns
                // (MR-820): when shutdown wins this select!, it is detached, not
                // cancelled.
                result = tokio::task::spawn_blocking({
                    let fd = Arc::clone(&tun_fd);
                    let buf = std::mem::take(&mut read_buf);
                    move || tun_read_owned(fd.as_raw_fd(), buf)
                }) => {
                    if let Ok((buf, n)) = result {
                        // Hand the buffer back for the next iteration BEFORE
                        // looking at the result, so every path reuses it.
                        read_buf = buf;
                        if let Some(n) = n {
                            did_work = true;
                            // Linux TUN with IFF_NO_PI: data is already a raw IP packet
                            let ip_packet = &read_buf[..n];
                            let packet_len = ip_packet.len() as u64;

                            if let Some(session) = wg_session.read().await.as_ref() {
                                match session.send_packet(ip_packet).await {
                                    Ok(_) => {
                                        bytes_sent.fetch_add(packet_len, Ordering::Relaxed);
                                        packets_sent.fetch_add(1, Ordering::Relaxed);
                                    }
                                    Err(e) => {
                                        tracing::debug!("Failed to send WG packet: {}", e);
                                    }
                                }
                            }
                        }
                    }
                }
            }

            // Read from WireGuard and write decrypted packets to TUN
            for _ in 0..MAX_BATCH_SIZE {
                if let Some(session) = wg_session.read().await.as_ref() {
                    if let Ok(Some(decrypted)) = session.recv_packet().await {
                        did_work = true;
                        let packet_len = decrypted.len() as u64;

                        // Linux TUN with IFF_NO_PI: write raw IP packet directly (no header)
                        let fd = Arc::clone(&tun_fd);
                        let buf = decrypted;
                        let buf_len = buf.len();
                        let write_result = tokio::task::spawn_blocking(move || {
                            let written = unsafe {
                                libc::write(
                                    fd.as_raw_fd(),
                                    buf.as_ptr() as *const libc::c_void,
                                    buf.len(),
                                )
                            };
                            if written < 0 {
                                tracing::debug!(
                                    "TUN write error: {}",
                                    std::io::Error::last_os_error()
                                );
                            } else if (written as usize) < buf.len() {
                                tracing::warn!(
                                    "Partial TUN write: {} of {} bytes",
                                    written,
                                    buf.len()
                                );
                            }
                            written
                        })
                        .await;

                        // Only count statistics when the full packet was written to TUN.
                        // Partial writes or errors must not inflate received counters.
                        if let Ok(written) = write_result {
                            if written >= 0 && (written as usize) == buf_len {
                                bytes_received.fetch_add(packet_len, Ordering::Relaxed);
                                packets_received.fetch_add(1, Ordering::Relaxed);
                            }
                        }
                    } else {
                        break; // nothing queued — stop draining
                    }
                } else {
                    break;
                }
            }

            // Drive boringtun's timers — WITHOUT this the session dies.
            //
            // boringtun advances all session state inside update_timers():
            // persistent keepalives, REKEY_AFTER_TIME rekeys, and dead-peer
            // detection. `encapsulate` reads the current keypair with no age
            // check, so once the server discards it at REJECT_AFTER_TIME the
            // client keeps happily encrypting to a session that no longer exists
            // — upload appears to work, download stops, and there is no
            // client-side recovery. Windows found this (FIX-DL, tunnel.rs:1834)
            // and fixed it; the Unix tunnels were never given the same tick, so
            // the keepalive plumbed in at start() was never actually emitted.
            //
            // The fd is O_NONBLOCK, so this is reached every iteration even when
            // the tunnel is completely idle — which is exactly when it matters.
            if last_timer_update.elapsed() >= TIMER_INTERVAL {
                last_timer_update = std::time::Instant::now();
                if let Some(session) = wg_session.read().await.as_ref() {
                    if let Err(e) = session.update_timers().await {
                        tracing::trace!("Timer update error: {}", e);
                    }
                }
            }

            if did_work {
                idle_cycles = 0;
            } else {
                idle_cycles = idle_cycles.saturating_add(1);
                if idle_cycles > DEEP_IDLE_THRESHOLD {
                    tokio::time::sleep(std::time::Duration::from_micros(DEEP_POLL_US)).await;
                } else if idle_cycles > IDLE_THRESHOLD {
                    tokio::time::sleep(std::time::Duration::from_micros(SLOW_POLL_US)).await;
                }
            }
        }

        tracing::info!("Packet loop exited");
    }
}

/// One blocking TUN read into an OWNED buffer that is handed straight back,
/// so the packet loop reuses a single allocation for the whole session (F6).
///
/// Returns `(buf, Some(n))` when `n > 0` bytes landed in `buf[..n]`, and
/// `(buf, None)` on EAGAIN (nothing queued on the O_NONBLOCK fd), EOF, or an
/// error (logged unless it is EAGAIN). `buf` comes back with its length and
/// allocation untouched in every case — the caller slices `&buf[..n]`
/// instead of truncating, which is what keeps the next read full-size
/// without a reallocation.
fn tun_read_owned(fd: i32, mut buf: Vec<u8>) -> (Vec<u8>, Option<usize>) {
    let n = unsafe { libc::read(fd, buf.as_mut_ptr() as *mut libc::c_void, buf.len()) };
    let got = if n > 0 {
        Some(n as usize)
    } else {
        if n < 0 {
            let err = std::io::Error::last_os_error();
            if err.raw_os_error() != Some(libc::EAGAIN) {
                tracing::debug!("TUN read error: {}", err);
            }
        }
        None
    };
    (buf, got)
}

/// F6: the packet loop's read helper must reuse its buffer. Exercised on a
/// pipe (any fd works for `read(2)`) on the ubuntu leg of tests.yml — no TUN
/// device or root needed. MR-820's fd-lifetime tests live here too, for the
/// same reason (`device_fd`'s own tests cover the protocol on every platform),
/// as does the TUN fd's close-on-exec check (the clone device opens unprivileged).
#[cfg(test)]
mod tun_read_tests {
    use super::tun_read_owned;

    /// (read_fd, write_fd), both O_CLOEXEC. The xray tests in the same run
    /// spawn child processes, and a child forked while a plain pipe() end is
    /// open inherits it and keeps it open — the closed-read-end checks below
    /// would then see a live reader that is not the test's.
    fn cloexec_pipe() -> (i32, i32) {
        let mut fds = [0i32; 2];
        assert_eq!(unsafe { libc::pipe2(fds.as_mut_ptr(), libc::O_CLOEXEC) }, 0);
        (fds[0], fds[1])
    }

    /// (read_fd, write_fd), read end O_NONBLOCK like the real TUN fd.
    fn nonblocking_pipe() -> (i32, i32) {
        let (r, w) = cloexec_pipe();
        let flags = unsafe { libc::fcntl(r, libc::F_GETFL) };
        assert!(flags >= 0);
        assert_eq!(
            unsafe { libc::fcntl(r, libc::F_SETFL, flags | libc::O_NONBLOCK) },
            0
        );
        (r, w)
    }

    fn write_all(fd: i32, bytes: &[u8]) {
        let n = unsafe { libc::write(fd, bytes.as_ptr() as *const libc::c_void, bytes.len()) };
        assert_eq!(n as usize, bytes.len());
    }

    /// The regression this helper exists to prevent: the old closure built a
    /// fresh 64 KiB Vec per iteration and `truncate`d it to the packet. Across
    /// many reads the SAME allocation must come back, full length, with the
    /// packet in its prefix.
    #[test]
    fn buffer_is_reused_across_reads_without_reallocation_or_truncation() {
        const CAP: usize = 65536;
        let (r, w) = nonblocking_pipe();
        let mut buf = vec![0u8; CAP];
        let original_ptr = buf.as_ptr();

        for i in 0..1_000u32 {
            let packet = i.to_le_bytes();
            write_all(w, &packet);
            let (returned, n) = tun_read_owned(r, buf);
            buf = returned;
            assert_eq!(n, Some(4), "iteration {i}");
            assert_eq!(&buf[..4], &packet, "iteration {i}");
            assert_eq!(buf.len(), CAP, "iteration {i}: length must not shrink");
            assert!(
                std::ptr::eq(buf.as_ptr(), original_ptr),
                "iteration {i}: the buffer was reallocated"
            );
        }

        unsafe {
            libc::close(w);
            libc::close(r);
        }
    }

    /// An idle O_NONBLOCK fd (EAGAIN) and a closed writer (EOF) both yield
    /// None — and still hand the buffer back intact, so the idle-poll path
    /// (the most frequent one before backoff) allocates nothing either.
    #[test]
    fn eagain_and_eof_return_none_but_keep_the_buffer() {
        let (r, w) = nonblocking_pipe();
        let buf = vec![0u8; 4096];
        let ptr = buf.as_ptr();

        let (buf, n) = tun_read_owned(r, buf);
        assert_eq!(n, None, "nothing written yet: EAGAIN");
        assert_eq!(buf.len(), 4096);
        assert!(std::ptr::eq(buf.as_ptr(), ptr));

        unsafe { libc::close(w) };
        let (buf, n) = tun_read_owned(r, buf);
        assert_eq!(n, None, "writer closed: EOF");
        assert_eq!(buf.len(), 4096);
        assert!(std::ptr::eq(buf.as_ptr(), ptr));

        unsafe { libc::close(r) };
    }

    /// A packet larger than the buffer is clipped to the buffer (read(2)
    /// semantics) — n never exceeds len, so `&buf[..n]` cannot panic.
    #[test]
    fn read_never_reports_more_than_the_buffer_holds() {
        let (r, w) = nonblocking_pipe();
        write_all(w, &[0xAB; 100]);
        let (buf, n) = tun_read_owned(r, vec![0u8; 64]);
        assert_eq!(n, Some(64));
        assert!(buf.iter().all(|&b| b == 0xAB));
        unsafe {
            libc::close(w);
            libc::close(r);
        }
    }

    /// Writing to a pipe whose read end is gone fails with EPIPE (Rust
    /// ignores SIGPIPE), which is how these tests see that the read end — the
    /// stand-in for the TUN fd — was really closed. Retried for a moment: even
    /// with O_CLOEXEC, a child mid-spawn elsewhere in the run holds a copy of
    /// the fd table between its fork and its exec.
    fn read_end_is_closed(w: i32) -> bool {
        (0..200).any(|_| {
            let n = unsafe { libc::write(w, b"?".as_ptr() as *const libc::c_void, 1) };
            let closed =
                n == -1 && std::io::Error::last_os_error().raw_os_error() == Some(libc::EPIPE);
            if !closed {
                std::thread::sleep(std::time::Duration::from_millis(10));
            }
            closed
        })
    }

    /// MR-820: when stop()'s close runs out of patience with a read the loop
    /// detached (`close_when_idle` past its wait: Deferred), the fd's NUMBER
    /// must stay taken until that read lets go. The old raw `close(fd)` freed
    /// it at once, and pipe()/open() hand out the lowest free number — that
    /// one — so the late read landed on whatever the process opened next.
    #[tokio::test]
    async fn a_deferred_close_keeps_the_number_until_the_detached_read_lets_go() {
        use crate::vpn::device_fd::{close_when_idle, CloseOutcome, DeviceSlot};
        use std::os::fd::{AsRawFd, FromRawFd, OwnedFd};
        use std::sync::Arc;

        let (r, w) = nonblocking_pipe();
        let slot: DeviceSlot<OwnedFd> =
            tokio::sync::RwLock::new(Some(Arc::new(unsafe { OwnedFd::from_raw_fd(r) })));
        // A read the loop handed to the blocking pool, still holding the fd.
        let in_flight = Arc::clone(slot.read().await.as_ref().unwrap());

        assert_eq!(
            close_when_idle(&slot, std::time::Duration::from_millis(20)).await,
            CloseOutcome::Deferred
        );
        assert!(slot.read().await.is_none(), "stop()'s reference is gone");

        let (r2, w2) = nonblocking_pipe();
        assert_ne!(r2, r, "the held fd's number was handed out again");
        assert_ne!(w2, r, "the held fd's number was handed out again");
        // Still open (and, being held, still ours: nothing can reuse it).
        assert_ne!(
            unsafe { libc::fcntl(r, libc::F_GETFD) },
            -1,
            "closed while a read still held it"
        );

        // The detached read still reads ITS device, not a newcomer.
        write_all(w, b"x");
        let (buf, n) = tun_read_owned(in_flight.as_raw_fd(), vec![0u8; 8]);
        assert_eq!((n, buf[0]), (Some(1), b'x'));

        drop(in_flight); // the last holder closes it
        assert!(read_end_is_closed(w));
        unsafe {
            libc::close(w);
            libc::close(r2);
            libc::close(w2);
        }
    }

    /// Review of MR-820: the close above relies on every read returning at
    /// once, so a device fd that cannot be made non-blocking is refused, not
    /// warned about. A BLOCKING pipe with nothing in it stands in for an idle
    /// device: after set_nonblocking the read returns at once (EAGAIN) instead
    /// of hanging. A bad descriptor is an error, not a silent pass.
    #[test]
    fn set_nonblocking_makes_an_idle_read_return_and_refuses_a_bad_fd() {
        use crate::vpn::device_fd::set_nonblocking;

        let (r, w) = cloexec_pipe();
        assert_eq!(
            unsafe { libc::fcntl(r, libc::F_GETFL) } & libc::O_NONBLOCK,
            0,
            "the pipe starts out blocking"
        );

        set_nonblocking(r).expect("a valid fd");
        // Checked before reading, so a regression fails here instead of
        // hanging the job in a blocking read.
        assert_ne!(
            unsafe { libc::fcntl(r, libc::F_GETFL) } & libc::O_NONBLOCK,
            0,
            "O_NONBLOCK was not set"
        );
        let started = std::time::Instant::now();
        let (_, n) = tun_read_owned(r, vec![0u8; 8]);
        assert_eq!(n, None, "an idle read must come back empty (EAGAIN)");
        assert!(started.elapsed() < std::time::Duration::from_secs(1));

        unsafe {
            libc::close(w);
            libc::close(r);
        }
        assert!(
            set_nonblocking(-1).is_err(),
            "a bad fd passed as non-blocking"
        );
    }

    /// The TUN fd is close-on-exec, or a child spawned while the tunnel is up
    /// (a re-spawned xray) keeps a copy and `birdo0` outlives stop(). This
    /// opens the real /dev/net/tun through the function create_tun_device()
    /// uses; the clone device is mode 0666, and no TUNSETIFF is issued, so it
    /// needs no root and creates no interface.
    #[test]
    fn the_tun_clone_device_opens_close_on_exec() {
        use std::os::fd::{AsRawFd, FromRawFd, OwnedFd};

        let fd = super::open_tun_clone().expect("open /dev/net/tun");
        // SAFETY: just opened, and owned by nothing else.
        let fd = unsafe { OwnedFd::from_raw_fd(fd) };
        let flags = unsafe { libc::fcntl(fd.as_raw_fd(), libc::F_GETFD) };
        assert!(flags >= 0, "F_GETFD: {}", std::io::Error::last_os_error());
        assert_ne!(
            flags & libc::FD_CLOEXEC,
            0,
            "the TUN fd is inherited by every child spawned while it is open"
        );
    }

    /// MR-820: stop()'s close waits for the blocking read the loop detached,
    /// then closes — the read runs against its own, still-open fd.
    #[tokio::test]
    async fn the_close_waits_for_a_detached_read_then_closes() {
        use crate::vpn::device_fd::{close_when_idle, CloseOutcome, DeviceSlot, IN_FLIGHT_WAIT};
        use std::os::fd::{AsRawFd, FromRawFd, OwnedFd};
        use std::sync::Arc;

        let (r, w) = nonblocking_pipe();
        let slot: DeviceSlot<OwnedFd> =
            tokio::sync::RwLock::new(Some(Arc::new(unsafe { OwnedFd::from_raw_fd(r) })));
        write_all(w, b"x");

        // A read handed to the blocking pool that has not run yet.
        let fd = Arc::clone(slot.read().await.as_ref().unwrap());
        let read = std::thread::spawn(move || {
            std::thread::sleep(std::time::Duration::from_millis(100));
            tun_read_owned(fd.as_raw_fd(), vec![0u8; 8])
        });

        let started = std::time::Instant::now();
        assert_eq!(
            close_when_idle(&slot, IN_FLIGHT_WAIT).await,
            CloseOutcome::Closed
        );
        assert!(
            started.elapsed() >= std::time::Duration::from_millis(80),
            "closed before the detached read ran"
        );
        let (buf, n) = read.join().unwrap();
        assert_eq!((n, buf[0]), (Some(1), b'x'));
        assert!(read_end_is_closed(w));
        unsafe { libc::close(w) };
    }
}

/// LAST-RESORT teardown, mirroring UtunTunnel's Drop (tunnel_macos.rs). start()
/// now unwinds its own error returns, but the manager wraps create()+start() in
/// CONNECT_TIMEOUT and DROPS the future on expiry — no error path ever runs,
/// the half-built tunnel is simply dropped. Without a Drop the TUN fd leaked,
/// and a leaked fd keeps birdo0 alive still owning the 0.0.0.0/1 + 128.0.0.0/1
/// half-defaults with no packet loop behind them: a total IPv4 blackhole the
/// user cannot recover from inside the app, plus one leaked descriptor per
/// failed connect. Closing the fd destroys the device and the kernel withdraws
/// every route through it.
impl Drop for LinuxTunnel {
    fn drop(&mut self) {
        // A packet loop still running (a tunnel dropped without stop()) holds
        // its own reference to the fd: stop it so it lets go. Its shutdown
        // sender goes with this struct, which also ends its select!.
        self.running.store(false, Ordering::SeqCst);
        // Routes this session added that nothing has removed yet: a start()
        // cancelled after configure_routes. Closing the fd withdraws the
        // routes THROUGH the device, but not the endpoint host route (relay
        // /32 via the uplink) or the LAN-sharing routes, which used to outlive
        // every such drop pointing at whatever gateway the host had then.
        // Removed first, as stop() does, and qualified the same way.
        let routes = take_owned_routes(&self.owned_routes);
        if !routes.is_empty() {
            tracing::warn!(
                "LinuxTunnel dropped with {} route(s) still installed — removing them",
                routes.len()
            );
            remove_owned_routes(routes);
        }
        // Drop cannot await. try_write is enough: by the time the tunnel is
        // being dropped nothing else legitimately holds this lock, and failing
        // to acquire it must never panic or block a teardown.
        let fd = match self.tun_fd.try_write() {
            Ok(mut guard) => guard.take(),
            Err(_) => None,
        };
        let Some(fd) = fd else {
            return; // stop()/unwind already ran — nothing leaked
        };
        // Drop cannot wait for in-flight I/O (no await), and with the fd
        // shared it does not need to (MR-820): letting go of our reference
        // closes it now, or — if a blocking read/write or the exiting loop
        // still holds it — the moment that returns. Never under a syscall that
        // is still using the number, and never twice. This used to close the
        // raw fd outright and accept the recycle race as the price of not
        // leaving the device alive (a guaranteed IPv4 blackhole).
        drop(fd);
        tracing::warn!(
            "LinuxTunnel dropped with the TUN fd still open — released it to \
             destroy the device and release its routes"
        );
        // A cancellation can also strike after /etc/resolv.conf was pinned but
        // before running ever became true — the pinned file outlives the
        // device and leaves every lookup on the machine pointing at tunnel
        // resolvers that no longer exist. Restore the backup, but only when
        // the file is provably ours.
        if resolv_conf_is_ours() {
            if let Ok(guard) = self.network_snapshot.try_read() {
                if let Some(snap) = guard.as_ref() {
                    let mut snap = snap.clone();
                    snap.resolv_conf_pinned = true;
                    crate::vpn::dns_journal::settle(
                        restore_dns(&snap),
                        crate::vpn::dns_journal::clear,
                    );
                }
            }
        }
    }
}

